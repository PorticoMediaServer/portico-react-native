#!/usr/bin/env node
// The words Android and iOS show for the apps, generated from the shared catalogue:
//
//   apps/native/android/app/src/main/res/values-<qualifier>/strings.xml   download channel and notification
//   apps/native/ios/Portico/<locale>.lproj/InfoPlist.strings              the local network permission prompt
//   values/strings.xml and Info.plist                                       the same messages' English
//
// and the Xcode project's InfoPlist.strings variant group and known regions, so each file ships.
//
//   node scripts/platform-strings.mjs --check    # fail if any generated file differs
//   node scripts/platform-strings.mjs --write
//
// A language gets files once the catalogue translates these messages; until then the system shows
// the English in values/strings.xml and Info.plist. A regional variant gets its own files only where
// it words a message differently from its base: Android and iOS already fall back from fr-CA to fr.
import {createHash} from 'node:crypto';
import {existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {enUS, formatMessage, translatedLocales} from '../packages/i18n/src/index.ts';
import {catalogue, variantBase} from '../packages/i18n/src/catalog/index.ts';
import '../packages/i18n/src/catalog/bundled.ts';

const here = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const res = path.join(here, 'apps/native/android/app/src/main/res');
const ios = path.join(here, 'apps/native/ios/Portico');
const pbxproj = path.join(here, 'apps/native/ios/Portico.xcodeproj/project.pbxproj');

const android = {downloads_channel: 'platform.downloadsChannel', downloads_running: 'platform.downloadsRunning'};
const apple = {NSLocalNetworkUsageDescription: 'platform.localNetworkUsage'};

/** Android's resource qualifier for a catalogue locale (BCP 47 form where a plain one cannot say it). */
export function androidQualifier(locale) {
  if (locale === 'id') return 'in'; // Android's resource name for Indonesian
  const [language, second] = locale.split('-');
  if (!second) return language;
  if (/^[A-Z]{2}$/.test(second)) return `${language}-r${second}`;
  return `b+${language}+${second}`;
}

/** A locale's own words for the messages, or nothing where it has none (or only repeats its base). */
function words(locale, ids) {
  const own = catalogue(locale);
  const base = variantBase[locale] ? catalogue(variantBase[locale]) : undefined;
  const out = {};
  for (const [key, id] of Object.entries(ids)) {
    const text = own[id];
    if (text === undefined || (base && base[id] === text)) continue;
    out[key] = formatMessage(text);
  }
  return Object.keys(out).length ? out : undefined;
}

const androidEscape = text => text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/"/g, '\\"').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/\n/g, '\\n').replace(/^([@?])/, '\\$1');
const appleEscape = text => text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
const banner = 'Generated by scripts/platform-strings.mjs from packages/i18n. Do not edit.';

export function expectedFiles() {
  const files = new Map();
  for (const locale of translatedLocales) {
    const a = words(locale, android);
    if (a) files.set(path.join(res, `values-${androidQualifier(locale)}`, 'strings.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${banner} -->\n<resources>\n${Object.entries(a).map(([k, v]) => `    <string name="${k}">${androidEscape(v)}</string>`).join('\n')}\n</resources>\n`);
    const i = words(locale, apple);
    if (i) files.set(path.join(ios, `${locale}.lproj`, 'InfoPlist.strings'), `/* ${banner} */\n${Object.entries(i).map(([k, v]) => `"${k}" = "${appleEscape(v)}";`).join('\n')}\n`);
  }
  // The English the system shows by default is the catalogue's too.
  const defaults = path.join(res, 'values', 'strings.xml');
  let strings = readFileSync(defaults, 'utf8');
  for (const [key, id] of Object.entries(android)) strings = strings.replace(new RegExp(`(<string name="${key}">)[^<]*(</string>)`), (_, open, close) => open + androidEscape(formatMessage(enUS[id])) + close);
  files.set(defaults, strings);
  const plist = path.join(ios, 'Info.plist');
  let info = readFileSync(plist, 'utf8');
  for (const [key, id] of Object.entries(apple)) info = info.replace(new RegExp(`(<key>${key}</key>\\s*<string>)[^<]*(</string>)`), (_, open, close) => open + formatMessage(enUS[id]).replace(/&/g, '&amp;').replace(/</g, '&lt;') + close);
  files.set(plist, info);
  return files;
}

// Xcode project entries for InfoPlist.strings, under fixed IDs so a second run finds and replaces them.
const ID = 'A57AC1';
const groupId = `${ID}000000000000000000`;
const buildId = `${ID}000000000000000001`;
const refId = locale => ID + createHash('sha1').update(locale).digest('hex').slice(0, 18).toUpperCase();

export function expectedProject(source, locales) {
  let text = source.split('\n').filter(line => !line.includes(ID) || line.includes(`${groupId} /* InfoPlist.strings */ = {`)).join('\n');
  // The variant group block, if a previous run wrote one.
  text = text.replace(new RegExp(`\\n\\t\\t${groupId} /\\* InfoPlist.strings \\*/ = \\{[\\s\\S]*?\\n\\t\\t\\};`), '');
  text = text.replace(/\n\/\* Begin PBXVariantGroup section \*\/\n\/\* End PBXVariantGroup section \*\/\n/, '');
  const known = ['en', 'Base', ...locales].map(l => (/^[a-z]+$/i.test(l) ? l : `"${l}"`));
  text = text.replace(/knownRegions = \([\s\S]*?\);/, `knownRegions = (\n${known.map(l => `\t\t\t\t${l},`).join('\n')}\n\t\t\t);`);
  if (!locales.length) return text;
  text = text.replace('/* End PBXBuildFile section */', `\t\t${buildId} /* InfoPlist.strings in Resources */ = {isa = PBXBuildFile; fileRef = ${groupId} /* InfoPlist.strings */; };\n/* End PBXBuildFile section */`);
  text = text.replace('/* End PBXFileReference section */', `${locales.map(l => `\t\t${refId(l)} /* ${l} */ = {isa = PBXFileReference; lastKnownFileType = text.plist.strings; name = ${/^[a-z]+$/.test(l) ? l : `"${l}"`}; path = "${l}.lproj/InfoPlist.strings"; sourceTree = "<group>"; };`).join('\n')}\n/* End PBXFileReference section */`);
  text = text.replace(/(13B07FAE1A68108700A75B9A \/\* Portico \*\/ = \{\n\t\t\tisa = PBXGroup;\n\t\t\tchildren = \(\n)/, `$1\t\t\t\t${groupId} /* InfoPlist.strings */,\n`);
  text = text.replace(/(13B07F8E1A680F5B00A75B9A \/\* Resources \*\/ = \{\n\t\t\tisa = PBXResourcesBuildPhase;\n\t\t\tbuildActionMask = \d+;\n\t\t\tfiles = \(\n)/, `$1\t\t\t\t${buildId} /* InfoPlist.strings in Resources */,\n`);
  const group = `\t\t${groupId} /* InfoPlist.strings */ = {\n\t\t\tisa = PBXVariantGroup;\n\t\t\tchildren = (\n${locales.map(l => `\t\t\t\t${refId(l)} /* ${l} */,`).join('\n')}\n\t\t\t);\n\t\t\tname = InfoPlist.strings;\n\t\t\tpath = Portico;\n\t\t\tsourceTree = "<group>";\n\t\t};`;
  if (text.includes('/* Begin PBXVariantGroup section */')) text = text.replace('/* End PBXVariantGroup section */', `${group}\n/* End PBXVariantGroup section */`);
  else text = text.replace('/* Begin XCBuildConfiguration section */', `/* Begin PBXVariantGroup section */\n${group}\n/* End PBXVariantGroup section */\n\n/* Begin XCBuildConfiguration section */`);
  return text;
}

/** Generated files that no longer have a language behind them. */
function staleFiles(files) {
  const out = [];
  for (const dir of existsSync(res) ? readdirSync(res) : []) {
    const file = path.join(res, dir, 'strings.xml');
    if (dir.startsWith('values-') && existsSync(file) && readFileSync(file, 'utf8').includes(banner) && !files.has(file)) out.push(file);
  }
  for (const dir of existsSync(ios) ? readdirSync(ios) : []) {
    const file = path.join(ios, dir, 'InfoPlist.strings');
    if (dir.endsWith('.lproj') && existsSync(file) && !files.has(file)) out.push(file);
  }
  return out;
}

function main(mode) {
  if (mode !== '--check' && mode !== '--write') { console.error('usage: platform-strings.mjs --check | --write'); return 2; }
  const files = expectedFiles();
  const locales = [...files.keys()].filter(f => f.endsWith('InfoPlist.strings')).map(f => path.basename(path.dirname(f), '.lproj')).sort();
  const project = readFileSync(pbxproj, 'utf8');
  const wantProject = expectedProject(project, locales);
  const stale = staleFiles(files);
  let drift = stale.length + (project === wantProject ? 0 : 1);
  for (const [file, text] of files) if (!existsSync(file) || readFileSync(file, 'utf8') !== text) drift++, mode === '--check' && console.error(`platform-strings: ${path.relative(here, file)} is out of date`);
  if (mode === '--check') {
    for (const file of stale) console.error(`platform-strings: ${path.relative(here, file)} has no language behind it`);
    if (project !== wantProject) console.error('platform-strings: the Xcode project does not list the InfoPlist.strings languages');
    if (drift) { console.error('run: node scripts/platform-strings.mjs --write'); return 1; }
    console.log(`platform-strings: ${files.size} files current`);
    return 0;
  }
  for (const [file, text] of files) { mkdirSync(path.dirname(file), {recursive: true}); writeFileSync(file, text); }
  for (const file of stale) rmSync(path.dirname(file), {recursive: true});
  writeFileSync(pbxproj, wantProject);
  console.log(`platform-strings: wrote ${files.size} files for ${locales.length} languages`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(main(process.argv[2]));
